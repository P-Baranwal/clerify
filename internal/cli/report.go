var csvHeader = []string{
	"ID", "Title", "Type", "Status", "Priority Score",
	"Estimated Hours", "Actual Hours", "Deadline", "Created", "Updated",
}

func (a *App) reportCmd() *cobra.Command {
	var (
		asCSV bool
		asMD  bool
		last  int
	)
	cmd := &cobra.Command{
		Use:   "report [section...]",
		Short: "Analytics: velocity, accuracy, projects, streaks, calibration, insights",
		Args:  cobra.ArbitraryArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.ensure(); err != nil {
				return err
			}

			if asCSV {
				return writeCSV(a.Out, a.DB.Items())
			}

			data := render.ReportData{
				Items:                a.DB.Items(),
				Projects:             a.DB.Projects(),
				Now:                  a.now(),
				AvailableHoursPerDay: a.DB.Data.Profile.AvailableHoursPerDay,
			}

			if a.flags.JSON {
				return a.printJSON(buildReportJSON(data))
			}
			if asMD {
				fmt.Fprint(a.Out, "<!-- generated by clerify -->\n")
			}
			render.Report(a.Out, data, args)
			return nil
		},
	}
	cmd.Flags().BoolVar(&asCSV, "csv", false, "emit the item CSV instead of the report")
	cmd.Flags().BoolVar(&asMD, "md", false, "prefix markdown output")
	cmd.Flags().IntVar(&last, "last", 8, "weeks of history")
	return cmd
}

func buildReportJSON(d render.ReportData) map[string]any {
	completed := 0
	for _, it := range d.Items {
		if it.IsDone() {
			completed++
		}
	}
	return map[string]any{
		"generatedAt": model.NowRFC3339(d.Now),
		"summary": map[string]any{
			"total":      len(d.Items),
			"completed":  completed,
			"streakDays": derive.Streak(d.Items, d.Now),
		},
		"velocity":    derive.Velocity(d.Items, d.Now, 8),
		"accuracy":    derive.Accuracy(d.Items),
		"projects":    derive.ProjectBreakdown(d.Items, d.Projects, d.Now, 30),
		"calibration": derive.Calibration(d.Items, 4),
		"insights":    derive.BuildInsights(d.Items),
		"risk":        derive.Risk(d.Items, d.Now, d.AvailableHoursPerDay),
	}
}

func (a *App) digestCmd() *cobra.Command {
	var week bool
	cmd := &cobra.Command{
		Use:   "digest",
		Short: "One-screen summary, suitable for cron",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.ensure(); err != nil {
				return err
			}
			now := a.now()
			fmt.Fprintf(a.Out, "clerify digest  %s\n\n", now.Format(model.DateLayout))

			overdue, dueToday := 0, 0
			for _, it := range a.DB.Items() {
				if it.IsDone() || it.Deadline == nil {
					continue
				}
				if model.IsOverdue(*it.Deadline, now) {
					overdue++
				} else if days, ok := model.DaysUntil(*it.Deadline, now); ok && days == 0 {
					dueToday++
				}
			}
			fmt.Fprintf(a.Out, "Overdue: %d   Due today: %d   Open: %d\n", overdue, dueToday, len(derive.PriorityList(a.DB.Items())))

			risk := derive.Risk(a.DB.Items(), now, a.DB.Data.Profile.AvailableHoursPerDay)
			if risk.Overloaded {
				fmt.Fprintf(a.Out, "Overload: %sh due in 7d vs %sh capacity (%.2fx)\n",
					hours(risk.TotalHours), hours(risk.AvailableHours), risk.Ratio)
			}

			top := derive.PriorityList(a.DB.Items())
			if len(top) > 5 {
				top = top[:5]
			}
			if len(top) > 0 {
				fmt.Fprintln(a.Out, "\nTop priority:")
				for i, it := range top {
					due := "—"
					if it.Deadline != nil {
						due = *it.Deadline
					}
					fmt.Fprintf(a.Out, "  %d. %s  (%d, due %s)\n", i+1, it.Title, it.EffectiveScore(), due)
				}
			}

			if week {
				fmt.Fprintln(a.Out)
				render.Report(a.Out, render.ReportData{
					Items:                a.DB.Items(),
					Projects:             a.DB.Projects(),
					Now:                  now,
					AvailableHoursPerDay: a.DB.Data.Profile.AvailableHoursPerDay,
				}, []string{"velocity"})
			}
			return nil
		},
	}
	cmd.Flags().BoolVar(&week, "week", false, "also include the velocity table")
	return cmd
}

func (a *App) exportCmd() *cobra.Command {
	var (
		asJSON bool
		asCSV  bool
		asICS  bool
		out    string
	)
	cmd := &cobra.Command{
		Use:   "export",
		Short: "Dump the store or item data",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.ensure(); err != nil {
				return err
			}

			w := a.Out
			if strings.TrimSpace(out) != "" {
				f, err := os.Create(out)
				if err != nil {
					return err
				}
				defer f.Close()
				w = f
			}

			switch {
			case asCSV:
				return writeCSV(w, a.DB.Items())
			case asICS:
				return writeICS(w, a.DB.Items(), a.now())
			default:
				_ = asJSON
				enc := json.NewEncoder(w)
				enc.SetIndent("", "  ")
				return enc.Encode(a.DB.Data)
			}
		},
	}
	cmd.Flags().BoolVar(&asJSON, "json", false, "native store JSON (default)")
	cmd.Flags().BoolVar(&asCSV, "csv", false, "item CSV")
	cmd.Flags().BoolVar(&asICS, "ics", false, "iCalendar feed with deadlines")
	cmd.Flags().StringVar(&out, "out", "", "write to a file instead of stdout")
	return cmd
}

func (a *App) importCmd() *cobra.Command {
	var (
		merge   bool
		fromCSV bool
	)
	cmd := &cobra.Command{
		Use:   "import <file>",
		Short: "Restore a store, a web-app export, or a CSV",
		Args:  exactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.ensure(); err != nil {
				return err
			}
			return a.runImport(args[0], merge, fromCSV)
		},
	}
	cmd.Flags().BoolVar(&merge, "merge", false, "merge by id instead of replacing everything")
	cmd.Flags().BoolVar(&fromCSV, "from-csv", false, "treat the file as an item CSV")
	return cmd
}

func (a *App) runImport(path string, merge, fromCSV bool) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return fail(2, err)
	}

	var incoming model.Store
	var warnings []string

	switch {
	case fromCSV:
		items, err := parseCSV(data)
		if err != nil {
			return fail(2, err)
		}
		incoming = model.Store{Items: items}
	case store.IsLegacyExport(data):
		res, err := store.ParseLegacy(data)
		if err != nil {
			return err
		}
		incoming = res.Store
		warnings = res.Warnings
	case store.IsNativeStore(data):
		if err := json.Unmarshal(data, &incoming); err != nil {
			return fail(2, fmt.Errorf("parse store: %w", err))
		}
		if incoming.SchemaVersion > model.SchemaVersion {
			return fail(2, fmt.Errorf("file schema %d is newer than this binary (%d)", incoming.SchemaVersion, model.SchemaVersion))
		}
	default:
		return fail(2, errors.New("unrecognised file: expected a clerify store, a web-app export, or --from-csv"))
	}

	for _, w := range warnings {
		if !a.flags.Quiet {
			fmt.Fprintln(a.Err, "warning:", w)
		}
	}

	if !a.flags.Yes && !a.confirm(fmt.Sprintf("Import %d item(s) and %d project(s)?", len(incoming.Items), len(incoming.Projects))) {
		return fail(1, errors.New("aborted (pass --yes to skip confirmation)"))
	}

	backup, err := a.backupStore()
	if err != nil {
		return err
	}

	added, replaced := 0, 0
	if merge {
		added, replaced, err = a.DB.UpsertItems(incoming.Items)
		if err != nil {
			return err
		}
		for _, p := range incoming.Projects {
			if _, ok := a.DB.ProjectByID(p.ID); ok {
				if _, err := a.DB.UpdateProject(p); err != nil {
					return err
				}
				continue
			}
			if _, err := a.DB.AddProject(p); err != nil {
				return err
			}
		}
	} else {
		if err := a.DB.ReplaceItems(incoming.Items); err != nil {
			return err
		}
		if err := a.DB.ReplaceProjects(incoming.Projects); err != nil {
			return err
		}
		if incoming.Profile.Skills != "" || incoming.Profile.PriorityPreset != "" {
			if _, err := a.DB.SetProfile(incoming.Profile); err != nil {
				return err
			}
		}
		added = len(incoming.Items)
	}

	if a.flags.JSON {
		return a.printJSON(map[string]any{
			"mode":     map[bool]string{true: "merge", false: "replace"}[merge],
			"items":    len(incoming.Items),
			"added":    added,
			"replaced": replaced,
			"projects": len(incoming.Projects),
			"backup":   backup,
		})
	}
	a.printf("imported %d item(s), %d project(s)", len(incoming.Items), len(incoming.Projects))
	if merge {
		a.printf(" (%d added, %d replaced)", added, replaced)
	}
	a.printf("\n")
	if backup != "" {
		a.printf("previous store saved to %s\n", backup)
	}
	return nil
}

func (a *App) backupStore() (string, error) {
	data, err := os.ReadFile(a.Paths.StoreFile)
	if err != nil {
		if os.IsNotExist(err) {
			return "", nil
		}
		return "", err
	}
	target := filepath.Join(a.Paths.Dir, "store.json.bak."+a.now().Format("20060102-150405"))
	return target, os.WriteFile(target, data, 0o600)
}

func writeCSV(w io.Writer, items []model.Item) error {
	cw := csv.NewWriter(w)
	if err := cw.Write(csvHeader); err != nil {
		return err
	}
	for _, it := range items {
		deadline := ""
		if it.Deadline != nil {
			deadline = *it.Deadline
		}
		actual := ""
		if it.ActualHours != 0 {
			actual = formatNum(it.ActualHours)
		}
		row := []string{
			it.ID,
			it.Title,
			it.Type,
			it.Status,
			fmt.Sprintf("%d", it.PriorityScore),
			formatNum(it.EstimatedHours),
			actual,
			deadline,
			it.CreatedAt,
			it.UpdatedAt,
		}
		if err := cw.Write(row); err != nil {
			return err
		}
	}
	cw.Flush()
	return cw.Error()
}

func parseCSV(data []byte) ([]model.Item, error) {
	r := csv.NewReader(strings.NewReader(string(data)))
	r.FieldsPerRecord = -1
	records, err := r.ReadAll()
	if err != nil {
		return nil, err
	}
	if len(records) == 0 {
		return nil, errors.New("empty CSV")
	}

	items := make([]model.Item, 0, len(records)-1)
	for _, row := range records[1:] {
		if len(row) < 4 {
			continue
		}
		it := model.NewItem(row[1])
		if strings.TrimSpace(row[0]) != "" {
			it.ID = strings.TrimSpace(row[0])
		}
		it.Title = row[1]
		it.Type = model.NormalizeType(row[2])
		it.Status = model.NormalizeStatus(row[3])
		if len(row) > 4 && strings.TrimSpace(row[4]) != "" {
			it.PriorityScore = atoiOr(row[4], model.DefaultPriority)
		}
		if len(row) > 5 && strings.TrimSpace(row[5]) != "" {
			it.EstimatedHours = atofOr(row[5], model.DefaultEstimatedHours)
		}
		if len(row) > 6 && strings.TrimSpace(row[6]) != "" {
			it.ActualHours = atofOr(row[6], 0)
		}
		if len(row) > 7 && strings.TrimSpace(row[7]) != "" {
			due := strings.TrimSpace(row[7])
			it.Deadline = &due
		}
		if len(row) > 8 {
			it.CreatedAt = strings.TrimSpace(row[8])
		}
		if len(row) > 9 {
			it.UpdatedAt = strings.TrimSpace(row[9])
		}
		items = append(items, it)
	}
	return items, nil
}

func writeICS(w io.Writer, items []model.Item, now time.Time) error {
	fmt.Fprintln(w, "BEGIN:VCALENDAR")
	fmt.Fprintln(w, "VERSION:2.0")
	fmt.Fprintln(w, "PRODID:-//clerify//EN")
	fmt.Fprintln(w, "CALSCALE:GREGORIAN")

	stamp := now.UTC().Format("20060102T150405Z")
	for _, it := range items {
		if it.Deadline == nil || *it.Deadline == "" {
			continue
		}
		t, ok := model.ParseDeadline(*it.Deadline)
		if !ok {
			continue
		}
		status := "CONFIRMED"
		if it.IsDone() {
			status = "COMPLETED"
		}
		fmt.Fprintln(w, "BEGIN:VEVENT")
		fmt.Fprintf(w, "UID:%s@clerify\n", it.ID)
		fmt.Fprintf(w, "DTSTAMP:%s\n", stamp)
		fmt.Fprintf(w, "DTSTART;VALUE=DATE:%s\n", t.Format("20060102"))
		fmt.Fprintf(w, "SUMMARY:%s\n", icsEscape(it.Title))
		if it.Notes != "" {
			fmt.Fprintf(w, "DESCRIPTION:%s\n", icsEscape(it.Notes))
		}
		fmt.Fprintf(w, "STATUS:%s\n", status)
		fmt.Fprintln(w, "END:VEVENT")
	}
	fmt.Fprintln(w, "END:VCALENDAR")
	return nil
}

func icsEscape(s string) string {
	replacer := strings.NewReplacer(`\`, `\\`, ";", `\;`, ",", `\,`, "\n", `\n`)
	return replacer.Replace(s)
}

func formatNum(v float64) string {
	s := fmt.Sprintf("%.2f", v)
	s = strings.TrimRight(s, "0")
	return strings.TrimRight(s, ".")
}

func atoiOr(s string, fallback int) int {
	var v int
	if _, err := fmt.Sscanf(strings.TrimSpace(s), "%d", &v); err != nil {
		return fallback
	}
	return v
}

func atofOr(s string, fallback float64) float64 {
	var v float64
	if _, err := fmt.Sscanf(strings.TrimSpace(s), "%f", &v); err != nil {
		return fallback
	}
	return v
}
